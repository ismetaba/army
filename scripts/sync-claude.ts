/**
 * T11 — generate the Claude Code native layer (`.claude/`) from `agents/*.md`.
 *
 * `agents/` is the single source for every agent prompt: this script only maps each agent's
 * permission profile onto Claude Code tool names and wraps the prompt in the frontmatter the
 * harness expects. Nothing here restates a prompt that already lives in `agents/`.
 *
 * Output is deterministic — fixed key order, fixed file order, no timestamps — so running it
 * twice leaves `git status` clean. Files are only written when their content actually changes.
 *
 * Usage:
 *   npx tsx scripts/sync-claude.ts          # write `.claude/`
 *   npx tsx scripts/sync-claude.ts --check  # exit 1 if anything would change (CI / T12)
 */
