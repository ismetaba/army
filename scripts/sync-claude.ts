/**
 * Emit a YAML scalar. Plain when it is unambiguous, double-quoted otherwise — a description
 * containing `: ` or a leading indicator character would otherwise change meaning or fail to parse.
 */
export function yamlScalar(value: string): string {
  const safe =
    /^[A-Za-z0-9]/.test(value) &&
    !/: /.test(value) &&
    !/ #/.test(value) &&
    !/[\n\r\t]/.test(value) &&
    !/[:#]$/.test(value) &&
    value.trim() === value;
  if (safe) return value;
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, ' ')}"`;
}

/** `.claude/agents/<name>.md` — frontmatter + the agent's own prompt (body + guardrails). */
export function renderAgent(agent: Agent): string {
  const lines = [
    '---',
    `# ${AGENT_MARKER}`,
    `name: ${agent.name}`,
    `description: ${yamlScalar(agent.description)}`,
    `tools: ${PROFILE_TOOLS[agent.profile].join(', ')}`,
    '---',
    '',
    agent.system.trim(),
    '',
    NATIVE_NOTES[agent.profile],
    '',
  ];
  return lines.join('\n');
}

/** `.claude/commands/<name>.md` — frontmatter + the workflow the CLI actually implements. */
export function renderCommand(cmd: CommandSpec): string {
  const lines = ['---', `# ${COMMAND_MARKER}`, `description: ${yamlScalar(cmd.description)}`];
  lines.push(`argument-hint: ${yamlScalar(cmd.argumentHint)}`);
  if (cmd.allowedTools) lines.push(`allowed-tools: ${cmd.allowedTools.join(', ')}`);
  lines.push('---', '', cmd.body.trim(), '');
  return lines.join('\n');
}

