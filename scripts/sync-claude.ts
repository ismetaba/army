type Status = 'created' | 'updated' | 'unchanged' | 'removed';

interface Change {
  file: string;
  status: Status;
}

function relative(file: string): string {
  return path.relative(REPO_ROOT, file);
}

/** Was this file produced by this script? Only such files are ever overwritten or pruned. */
function isGenerated(file: string): boolean {
  try {
    return fs.readFileSync(file, 'utf8').includes(MARKER);
  } catch {
    return false;
  }
}

function syncFile(file: string, content: string, check: boolean): Change {
  let existing: string | undefined;
  try {
    existing = fs.readFileSync(file, 'utf8');
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
  }
  if (existing === content) return { file, status: 'unchanged' };
  if (existing !== undefined && !existing.includes(MARKER)) {
    throw new Error(
      `refusing to overwrite hand-written file ${relative(file)} — it carries no "${MARKER}" marker`,
    );
  }
  const status: Status = existing === undefined ? 'created' : 'updated';
  if (!check) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, 'utf8');
  }
  return { file, status };
}

/** Delete generated `.md` files in `dir` that the current run did not produce. */
function prune(dir: string, keep: ReadonlySet<string>, check: boolean): Change[] {
  let entries: string[];
  try {
    entries = fs.readdirSync(dir);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw err;
  }
  const removed: Change[] = [];
  for (const entry of entries.sort()) {
    const full = path.join(dir, entry);
    if (keep.has(full) || !entry.endsWith('.md') || !fs.statSync(full).isFile()) continue;
    // A file the developer wrote by hand is theirs; only our own leftovers are pruned.
    if (!isGenerated(full)) continue;
    if (!check) fs.rmSync(full);
    removed.push({ file: full, status: 'removed' });
  }
  return removed;
}

export interface SyncResult {
  changes: Change[];
  /** True when nothing on disk had to change. */
  clean: boolean;
}

export function sync(check = false): SyncResult {
  const agentsOut = path.join(CLAUDE_DIR, 'agents');
  const commandsOut = path.join(CLAUDE_DIR, 'commands');

  const changes: Change[] = [];
  const writtenAgents = new Set<string>();
  // `loadAllAgents()` returns them in `AgentName` order — stable across runs and machines.
  for (const agent of loadAllAgents()) {
    const file = path.join(agentsOut, `${agent.name}.md`);
    writtenAgents.add(file);
    changes.push(syncFile(file, renderAgent(agent), check));
  }

  const writtenCommands = new Set<string>();
  for (const cmd of [...COMMANDS].sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const file = path.join(commandsOut, `${cmd.name}.md`);
    writtenCommands.add(file);
    changes.push(syncFile(file, renderCommand(cmd), check));
  }

  changes.push(...prune(agentsOut, writtenAgents, check));
  changes.push(...prune(commandsOut, writtenCommands, check));

  return { changes, clean: changes.every((c) => c.status === 'unchanged') };
}

function main(argv: readonly string[]): void {
  const check = argv.includes('--check');
  const unknown = argv.filter((a) => a !== '--check');
  if (unknown.length > 0) {
    process.stderr.write(`unknown argument(s): ${unknown.join(' ')}\nusage: sync-claude [--check]\n`);
    process.exit(1);
  }

  let result: SyncResult;
  try {
    result = sync(check);
  } catch (err) {
    // AgentError (a malformed `agents/*.md`) and fs errors both land here as plain messages.
    const message = err instanceof Error ? err.message : String(err);
    process.stderr.write(`sync-claude failed: ${message}\n`);
    process.exit(1);
  }

  for (const change of result.changes) {
    process.stdout.write(`${change.status.padEnd(9)} ${relative(change.file)}\n`);
  }
  if (check && !result.clean) {
    process.stderr.write('.claude/ is out of date — run `npm run sync-claude`\n');
    process.exit(1);
  }
  process.stdout.write(result.clean ? '.claude/ is up to date\n' : '.claude/ synced\n');
}

